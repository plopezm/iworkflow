// Package storage keeps the images attached to tasks on the local file system.
//
// Every file operation goes through os.Root, which confines it to the attachments folder: a path that
// escapes it, through ".." or through a symbolic link, fails instead of reaching another file.
//
//nolint:wrapcheck // Port errors are returned unwrapped: their text is user-visible and must stay identical to the Rust version.
package storage

import (
	"context"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/google/uuid"

	werrors "iworkflow/internal/modules/tasks/domain/errors"
	"iworkflow/internal/modules/tasks/domain/models"
	"iworkflow/internal/modules/tasks/domain/ports/outbound"
)

// Permissions of the attachment folders and files. Attachments are user content: only the owner reads them.
const (
	dirPermission  os.FileMode = 0o700
	filePermission os.FileMode = 0o600
)

// FsAttachmentStorage stores each image as <dir>/<task id>/<attachment id>.<extension>. Attachment ids
// are UUIDs generated by the application, so a name written by this adapter never contains a separator.
type FsAttachmentStorage struct {
	dir string
}

var _ outbound.AttachmentStorage = (*FsAttachmentStorage)(nil)

// NewFsAttachmentStorage creates the folder when it is missing and returns the storage over it.
func NewFsAttachmentStorage(dir string) (*FsAttachmentStorage, error) {
	if err := os.MkdirAll(dir, dirPermission); err != nil {
		return nil, fmt.Errorf("create attachments folder: %w", err)
	}
	return &FsAttachmentStorage{dir: dir}, nil
}

// Save writes the decoded image and returns its path relative to the storage folder. The write goes to a
// temporary file that is renamed into place, so a reader never sees a partial image.
func (s *FsAttachmentStorage) Save(_ context.Context, taskID models.TaskID, attachmentID string, image models.ImageAttachment) (string, error) {
	extension, err := extensionFor(image.MimeType)
	if err != nil {
		return "", err
	}
	if !isCanonicalUUID(attachmentID) {
		return "", werrors.Storage("identificador de adjunto no válido: " + attachmentID)
	}
	if base64.StdEncoding.DecodedLen(len(image.Data)) > models.MaxImageBytes+4 {
		return "", werrors.Storage(image.Name + ": la imagen supera los 4 MiB")
	}
	data, err := base64.StdEncoding.DecodeString(image.Data)
	if err != nil {
		return "", werrors.Storage(fmt.Sprintf("%s: base64 inválido: %v", image.Name, err))
	}
	if len(data) > models.MaxImageBytes {
		return "", werrors.Storage(image.Name + ": la imagen supera los 4 MiB")
	}
	root, err := s.openRoot()
	if err != nil {
		return "", err
	}
	defer closeQuietly(root)

	taskDir := taskID.String()
	if err := root.MkdirAll(taskDir, dirPermission); err != nil {
		return "", werrors.Storage("no se pudo crear el directorio de adjuntos: " + err.Error())
	}
	relative := filepath.Join(taskDir, attachmentID+"."+extension)
	temporary := filepath.Join(taskDir, "."+uuid.NewString()+".tmp")
	if err := writeAtomically(root, temporary, relative, data); err != nil {
		return "", werrors.Storage("no se pudo guardar el adjunto: " + err.Error())
	}
	return relative, nil
}

// Read returns the content of the file encoded in base64.
func (s *FsAttachmentStorage) Read(ctx context.Context, path string) (string, error) {
	data, err := s.ReadBytes(ctx, path)
	if err != nil {
		return "", werrors.Storage(fmt.Sprintf("no se pudo leer el adjunto %s: %v", path, err))
	}
	return base64.StdEncoding.EncodeToString(data), nil
}

// ReadBytes returns the file as it is. A missing file is NotFound.
func (s *FsAttachmentStorage) ReadBytes(_ context.Context, path string) ([]byte, error) {
	relative, err := validRelativePath(path)
	if err != nil {
		return nil, err
	}
	root, err := s.openRoot()
	if err != nil {
		return nil, err
	}
	defer closeQuietly(root)

	file, err := root.Open(relative)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, werrors.NotFound("adjunto " + path)
	}
	if err != nil {
		return nil, werrors.Storage(fmt.Sprintf("no se pudo leer el adjunto %s: %v", path, err))
	}
	defer closeQuietly(file)

	info, err := file.Stat()
	if err != nil {
		return nil, werrors.Storage(fmt.Sprintf("no se pudo leer el adjunto %s: %v", path, err))
	}
	if !info.Mode().IsRegular() {
		return nil, werrors.Storage("el adjunto no es un fichero: " + path)
	}
	// One byte over the limit is read on purpose: it tells an oversized file from one at the limit.
	data, err := io.ReadAll(io.LimitReader(file, models.MaxImageBytes+1))
	if err != nil {
		return nil, werrors.Storage(fmt.Sprintf("no se pudo leer el adjunto %s: %v", path, err))
	}
	if len(data) > models.MaxImageBytes {
		return nil, werrors.Storage("el adjunto supera los 4 MiB: " + path)
	}
	return data, nil
}

// Delete removes one file. A file that is already gone is not an error.
func (s *FsAttachmentStorage) Delete(_ context.Context, path string) error {
	relative, err := validRelativePath(path)
	if err != nil {
		return err
	}
	root, err := s.openRoot()
	if err != nil {
		return err
	}
	defer closeQuietly(root)

	err = root.Remove(relative)
	if err == nil || errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	return werrors.Storage("no se pudo borrar el adjunto: " + err.Error())
}

// DeleteTaskDir removes the folder of one task and everything in it. A missing folder is not an error.
// A folder that is a symbolic link is removed as a link: the folder it points to is left alone.
func (s *FsAttachmentStorage) DeleteTaskDir(_ context.Context, taskID models.TaskID) error {
	root, err := s.openRoot()
	if err != nil {
		return err
	}
	defer closeQuietly(root)

	if err := root.RemoveAll(taskID.String()); err != nil {
		return werrors.Storage("no se pudo borrar el directorio de adjuntos: " + err.Error())
	}
	return nil
}

func (s *FsAttachmentStorage) openRoot() (*os.Root, error) {
	root, err := os.OpenRoot(s.dir)
	if err != nil {
		return nil, werrors.Storage("no se pudo abrir el directorio de adjuntos: " + err.Error())
	}
	return root, nil
}

// writeAtomically writes data to a temporary file in the same folder and renames it onto target. A
// failure removes the temporary file, so no partial image is left behind.
func writeAtomically(root *os.Root, temporary string, target string, data []byte) (err error) {
	file, err := root.OpenFile(temporary, os.O_WRONLY|os.O_CREATE|os.O_EXCL, filePermission)
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			// Best effort: the write error is the one reported, and the temporary name is unique anyway.
			_ = root.Remove(temporary)
		}
	}()
	_, writeErr := file.Write(data)
	syncErr := file.Sync()
	closeErr := file.Close()
	if err = errors.Join(writeErr, syncErr, closeErr); err != nil {
		return err
	}
	return root.Rename(temporary, target)
}

// validRelativePath accepts only a relative path that stays inside the storage folder. It is checked
// lexically here and confined again by os.Root when the file is opened.
func validRelativePath(path string) (string, error) {
	if path == "" || !filepath.IsLocal(path) || filepath.Clean(path) == "." {
		return "", werrors.Storage("ruta de adjunto no válida: " + path)
	}
	return path, nil
}

// extensionFor maps an accepted MIME type to its file extension.
func extensionFor(mimeType string) (string, error) {
	switch mimeType {
	case "image/png":
		return "png", nil
	case "image/jpeg":
		return "jpg", nil
	case "image/gif":
		return "gif", nil
	case "image/webp":
		return "webp", nil
	default:
		return "", werrors.Storage("tipo de imagen no admitido: " + mimeType)
	}
}

// isCanonicalUUID reports whether value is a UUID in its canonical lowercase form.
func isCanonicalUUID(value string) bool {
	parsed, err := uuid.Parse(value)
	return err == nil && parsed.String() == value
}

func closeQuietly(closer io.Closer) {
	// A close failure on a read-only handle or an already used root does not change the result.
	_ = closer.Close()
}
